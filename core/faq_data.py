def match_faq(text):
    """質問文に一番近いFAQを返す。 (entry, score)。一致が弱ければ (None, score)。"""
    normalized = ''.join((text or '').lower().split())
    best, best_score = None, 0
    for entry in FAQS:
        score = 0
        for keyword in entry['keywords']:
            if keyword in normalized:
                score += len(keyword)
        # 質問文そのものとの部分一致も少し加点
        q = ''.join(entry['question'].lower().split())
        for token in ('ポイント', '写真', 'チャット', '通知', '依頼', '評価', '招待'):
            if token in normalized and token in q:
                score += 1
        if score > best_score:
            best, best_score = entry, score
    if best_score < 3:
        return None, best_score
    return best, best_score
